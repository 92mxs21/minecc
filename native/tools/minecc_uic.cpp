// minecc-uic: Standalone Cross-Platform HTML5 + CSS3 + ES6 Compiler & Native Executable Packager
// Compiles declarative (.html + .css + .js) projects into:
//   1. Verified .muib (Minecc UI Bundle) binary packages (`-o app.muib`)
//   2. Self-contained C++20 embedded byte headers (`--emit-cpp generated_bundle.hpp`)
//   3. Instant standalone Windows .exe / Linux ELF executables (`--pack-exe <runtime> <out_exe>`)

#include <filesystem>
#include <fstream>
#include <iomanip>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>

#include "native/include/helios/bundle_format.hpp"
#include "native/include/helios/css_engine.hpp"
#include "native/include/helios/html_dom.hpp"
#include "native/include/helios/js_vm.hpp"

namespace fs = std::filesystem;

namespace {

std::string read_text_file(const fs::path& p) {
    std::ifstream f(p, std::ios::binary);
    if (!f) throw std::runtime_error("Cannot open source file: " + p.string());
    std::ostringstream ss;
    ss << f.rdbuf();
    return ss.str();
}

uint32_t count_dom_nodes(const std::shared_ptr<helios::DomNode>& n) {
    if (!n) return 0;
    uint32_t total = 1;
    for (const auto& c : n->children) total += count_dom_nodes(c);
    return total;
}

void write_cpp_header(const fs::path& out_path, const std::vector<uint8_t>& bytes) {
    fs::create_directories(out_path.parent_path());
    std::ofstream out(out_path);
    if (!out) throw std::runtime_error("Cannot write C++ header: " + out_path.string());
    out << "#pragma once\n"
        << "// Auto-generated by minecc-uic from declarative HTML5 + CSS3 + ES6 UI sources.\n"
        << "#include <cstddef>\n#include <cstdint>\n\n"
        << "namespace helios::embedded {\n"
        << "inline constexpr size_t DEFAULT_BUNDLE_SIZE = " << bytes.size() << "u;\n"
        << "inline constexpr uint8_t DEFAULT_BUNDLE[" << bytes.size() << "] = {\n";
    for (size_t i = 0; i < bytes.size(); ++i) {
        if (i % 24 == 0) out << "  ";
        out << static_cast<unsigned>(bytes[i]) << ",";
        if (i % 24 == 23) out << "\n";
    }
    out << "\n};\n} // namespace helios::embedded\n";
}

void pack_standalone_executable(const fs::path& runtime_bin, const fs::path& out_exe, const std::vector<uint8_t>& muib) {
    std::ifstream in(runtime_bin, std::ios::binary | std::ios::ate);
    if (!in) throw std::runtime_error("Cannot read template runtime binary: " + runtime_bin.string());
    auto sz = in.tellg();
    in.seekg(0);
    std::vector<uint8_t> exe_bytes(static_cast<size_t>(sz));
    in.read(reinterpret_cast<char*>(exe_bytes.data()), sz);

    // Strip existing HELIOSEX trailer if re-packing an already packed binary
    if (exe_bytes.size() >= 16 &&
        std::memcmp(exe_bytes.data() + exe_bytes.size() - 8, "HELIOSEX", 8) == 0)
    {
        size_t pos = exe_bytes.size() - 16;
        uint64_t prev_len = helios::bundle::read_u64_le(exe_bytes.data(), exe_bytes.size(), pos);
        if (prev_len + 16 < exe_bytes.size()) {
            exe_bytes.resize(exe_bytes.size() - static_cast<size_t>(prev_len) - 16);
        }
    }

    if (out_exe.has_parent_path()) fs::create_directories(out_exe.parent_path());
    std::ofstream out(out_exe, std::ios::binary);
    if (!out) throw std::runtime_error("Cannot create output executable: " + out_exe.string());

    out.write(reinterpret_cast<const char*>(exe_bytes.data()), static_cast<std::streamsize>(exe_bytes.size()));
    out.write(reinterpret_cast<const char*>(muib.data()), static_cast<std::streamsize>(muib.size()));

    std::vector<uint8_t> trailer;
    helios::bundle::write_u64_le(trailer, static_cast<uint64_t>(muib.size()));
    const char magic[8] = {'H', 'E', 'L', 'I', 'O', 'S', 'E', 'X'};
    trailer.insert(trailer.end(), magic, magic + 8);
    out.write(reinterpret_cast<const char*>(trailer.data()), static_cast<std::streamsize>(trailer.size()));
    out.close();

#ifndef _WIN32
    fs::permissions(out_exe, fs::perms::owner_exec | fs::perms::group_exec | fs::perms::others_exec, fs::perm_options::add);
#endif
}

} // namespace

int main(int argc, char** argv) {
    if (argc < 2) {
        std::cerr << "minecc-uic 0.2.0 — Minimal Cross-Platform HTML5 + CSS3 + JS Native Compiler\n"
                  << "Usage:\n"
                  << "  minecc-uic <entry.html> [-o <bundle.muib>] [--emit-cpp <header.hpp>]\n"
                  << "  minecc-uic <entry.html> --pack-exe <minecc-studio-bin> <custom-app.exe>\n";
        return 1;
    }

    fs::path entry_html;
    fs::path out_muib;
    fs::path out_cpp;
    fs::path runtime_exe;
    fs::path packed_out;

    for (int i = 1; i < argc; ++i) {
        std::string arg = argv[i];
        if (arg == "-o" && i + 1 < argc) out_muib = argv[++i];
        else if (arg == "--emit-cpp" && i + 1 < argc) out_cpp = argv[++i];
        else if (arg == "--pack-exe" && i + 2 < argc) {
            runtime_exe = argv[++i];
            packed_out = argv[++i];
        } else if (arg == "--version" || arg == "-v") {
            std::cout << "minecc-uic 0.2.0 (HeliosUI Native HTML5/CSS3/ES6 Compiler)\n";
            return 0;
        } else if (entry_html.empty()) {
            entry_html = arg;
        }
    }

    if (entry_html.empty()) {
        std::cerr << "[minecc-uic] Error: missing <entry.html> input file.\n";
        return 1;
    }

    try {
        std::string html_src = read_text_file(entry_html);
        fs::path base_dir = entry_html.parent_path();

        // Phase 1: HTML5 Spec Tokenizer & DOM Tree Verification
        auto doc = helios::parse_html_document(html_src);
        uint32_t dom_nodes = count_dom_nodes(doc.root);

        // Phase 2: Resolve linked <link rel="stylesheet"> & validate CSS3 Cascade Rules
        std::string combined_css;
        for (const auto& href : doc.linked_stylesheets) {
            combined_css += read_text_file(base_dir / href) + "\n";
        }
        for (const auto& inline_st : doc.inline_styles) {
            combined_css += inline_st + "\n";
        }
        auto sheet = helios::parse_stylesheet(combined_css);

        // Phase 3: Resolve <script src="..."> & validate ES6 AST via Recursive-Descent Parser
        std::string combined_js;
        for (const auto& sref : doc.linked_scripts) {
            combined_js += read_text_file(base_dir / sref) + "\n";
        }
        for (const auto& inline_js : doc.inline_scripts) {
            combined_js += inline_js + "\n";
        }
        auto tokens = helios::js::tokenize_js(combined_js);
        helios::js::Parser js_parser(std::move(tokens));
        auto ast = js_parser.parse_program();

        // Phase 4: Emit verified binary bundle (.muib)
        helios::bundle::BundlePayload payload;
        payload.entry_name = entry_html.filename().string();
        payload.html_source = html_src;
        payload.css_source = combined_css;
        payload.js_source = combined_js;
        payload.dom_node_estimate = dom_nodes;
        payload.css_rule_count = static_cast<uint32_t>(sheet.rules.size());

        auto muib_bytes = helios::bundle::serialize_bundle(payload);
        auto roundtrip = helios::bundle::deserialize_bundle(muib_bytes.data(), muib_bytes.size());

        if (!out_muib.empty()) {
            if (out_muib.has_parent_path()) fs::create_directories(out_muib.parent_path());
            std::ofstream f(out_muib, std::ios::binary);
            if (!f) throw std::runtime_error("Cannot write output bundle: " + out_muib.string());
            f.write(reinterpret_cast<const char*>(muib_bytes.data()), static_cast<std::streamsize>(muib_bytes.size()));
        }
        if (!out_cpp.empty()) {
            write_cpp_header(out_cpp, muib_bytes);
        }
        if (!runtime_exe.empty() && !packed_out.empty()) {
            pack_standalone_executable(runtime_exe, packed_out, muib_bytes);
        }

        std::cout << "[minecc-uic] Compiled '" << payload.entry_name << "' -> "
                  << dom_nodes << " DOM nodes, "
                  << sheet.rules.size() << " CSS3 rules, "
                  << ast->list.size() << " top-level ES6 statements | "
                  << muib_bytes.size() << " bytes (FNV-1a 0x"
                  << std::hex << roundtrip.fnv1a_checksum << std::dec << ")\n";
        return 0;
    } catch (const std::exception& ex) {
        std::cerr << "[minecc-uic] Compilation failed: " << ex.what() << "\n";
        return 2;
    }
}
