#!/usr/bin/env python3
"""Generate crisp FreeType2-hinted glyph atlases from permissive DejaVu fonts into C++."""

from __future__ import annotations

from pathlib import Path
import sys

from PIL import Image, ImageDraw, ImageFont

FONT_DIR = Path("/usr/share/fonts/truetype/dejavu")

FONT_SPECS = [
    ("SANS_11", FONT_DIR / "DejaVuSans.ttf", False, False, 11),
    ("SANS_12", FONT_DIR / "DejaVuSans.ttf", False, False, 12),
    ("SANS_13", FONT_DIR / "DejaVuSans.ttf", False, False, 13),
    ("SANS_BOLD_11", FONT_DIR / "DejaVuSans-Bold.ttf", True, False, 11),
    ("SANS_BOLD_12", FONT_DIR / "DejaVuSans-Bold.ttf", True, False, 12),
    ("SANS_BOLD_14", FONT_DIR / "DejaVuSans-Bold.ttf", True, False, 14),
    ("SANS_BOLD_18", FONT_DIR / "DejaVuSans-Bold.ttf", True, False, 18),
    ("MONO_11", FONT_DIR / "DejaVuSansMono.ttf", False, False, 11),
    ("MONO_12", FONT_DIR / "DejaVuSansMono.ttf", False, False, 12),
    ("MONO_13", FONT_DIR / "DejaVuSansMono.ttf", False, False, 13),
    ("MONO_BOLD_12", FONT_DIR / "DejaVuSansMono-Bold.ttf", True, False, 12),
    ("MONO_BOLD_13", FONT_DIR / "DejaVuSansMono-Bold.ttf", True, False, 13),
]

CODEPOINTS: list[int] = list(range(0x20, 0x7F)) + [
    0x00A7,  # §
    0x00B1,  # ±
    0x00B7,  # ·
    0x00D7,  # ×
    0x2013,  # –
    0x2014,  # —
    0x2022,  # •
    0x2026,  # …
    0x2190,  # ←
    0x2192,  # →
    0x21C4,  # ⇄
    0x25B8,  # ▸
    0x25BE,  # ▾
    0x2699,  # ⚙
    0x2713,  # ✓
]


def main() -> int:
    repo_root = Path(__file__).resolve().parents[1]
    out_header = repo_root / "native" / "generated" / "font_atlas.hpp"
    out_header.parent.mkdir(parents=True, exist_ok=True)

    raw_bitmap = bytearray()
    font_meta_lines: list[str] = []
    glyph_meta_lines: list[str] = []

    for font_idx, (enum_name, ttf_path, is_bold, _is_italic, px_size) in enumerate(FONT_SPECS):
        font = ImageFont.truetype(str(ttf_path), px_size)
        ascent, descent = font.getmetrics()
        line_height = ascent + descent + 3
        first_glyph_index = len(glyph_meta_lines)

        for cp in CODEPOINTS:
            ch = chr(cp)
            advance = max(1, int(round(font.getlength(ch))))
            bbox = font.getbbox(ch)
            if bbox is None or ch == " ":
                w, h, off_x, off_y, data_offset = 0, 0, 0, 0, len(raw_bitmap)
            else:
                x0, y0, x1, y1 = bbox
                w = max(0, x1 - x0)
                h = max(0, y1 - y0)
                if w == 0 or h == 0:
                    off_x, off_y, data_offset = 0, 0, len(raw_bitmap)
                else:
                    img = Image.new("L", (w, h), 0)
                    draw = ImageDraw.Draw(img)
                    draw.text((-x0, -y0), ch, fill=255, font=font)
                    data_offset = len(raw_bitmap)
                    raw_bitmap.extend(img.tobytes())
                    off_x = x0
                    off_y = y0

            glyph_meta_lines.append(
                f"    {{{cp}u, {w}, {h}, {off_x}, {off_y}, {advance}, {data_offset}u}},"
            )

        font_meta_lines.append(
            f"    {{{px_size}, {ascent}, {descent}, {line_height}, "
            f"{'true' if 'MONO' in enum_name else 'false'}, {'true' if is_bold else 'false'}, "
            f"{first_glyph_index}u, {len(CODEPOINTS)}u}}, // {enum_name} ({font_idx})"
        )

    hex_chunks: list[str] = []
    for i in range(0, len(raw_bitmap), 24):
        row = ", ".join(f"0x{b:02x}" for b in raw_bitmap[i : i + 24])
        hex_chunks.append(f"    {row},")

    header_text = f"""#pragma once
// Auto-generated by scripts/gen_font_atlas.py from DejaVu Sans & DejaVu Sans Mono.
// License: Bitstream Vera / DejaVu Fonts permissive license (see NOTICE.md).

#include <cstdint>

namespace helios::fonts {{

struct GlyphInfo {{
    uint32_t codepoint;
    int16_t width;
    int16_t height;
    int16_t bearing_x;
    int16_t bearing_y;
    int16_t advance;
    uint32_t alpha_offset;
}};

struct BakedFontFace {{
    int16_t px_size;
    int16_t ascent;
    int16_t descent;
    int16_t line_height;
    bool monospace;
    bool bold;
    uint32_t first_glyph;
    uint32_t glyph_count;
}};

inline constexpr uint32_t RAW_ALPHA_BYTES = {len(raw_bitmap)}u;
inline constexpr uint32_t FACE_COUNT = {len(FONT_SPECS)}u;

inline constexpr BakedFontFace FACES[FACE_COUNT] = {{
{chr(10).join(font_meta_lines)}
}};

inline constexpr GlyphInfo GLYPHS[{len(glyph_meta_lines)}] = {{
{chr(10).join(glyph_meta_lines)}
}};

inline constexpr uint8_t RAW_ALPHA[{len(raw_bitmap)}] = {{
{chr(10).join(hex_chunks)}
}};

inline int select_face(bool mono, bool bold, int requested_px) {{
    int best_idx = 0;
    int best_dist = 999999;
    for (uint32_t i = 0; i < FACE_COUNT; ++i) {{
        if (FACES[i].monospace != mono || FACES[i].bold != bold) continue;
        int d = FACES[i].px_size - requested_px;
        if (d < 0) d = -d;
        if (d < best_dist) {{
            best_dist = d;
            best_idx = static_cast<int>(i);
        }}
    }}
    return best_idx;
}}

inline const GlyphInfo* lookup_glyph(int face_idx, uint32_t cp) {{
    const auto& f = FACES[face_idx];
    uint32_t lo = f.first_glyph;
    uint32_t hi = f.first_glyph + f.glyph_count;
    while (lo < hi) {{
        uint32_t mid = lo + (hi - lo) / 2;
        if (GLYPHS[mid].codepoint == cp) return &GLYPHS[mid];
        if (GLYPHS[mid].codepoint < cp) lo = mid + 1;
        else hi = mid;
    }}
    if (cp != '?') return lookup_glyph(face_idx, '?');
    return nullptr;
}}

}} // namespace helios::fonts
"""
    out_header.write_text(header_text, encoding="utf-8")
    print(
        f"Generated {out_header} ({len(FONT_SPECS)} faces, {len(glyph_meta_lines)} glyphs, "
        f"{len(raw_bitmap):,} bytes direct .rodata)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
